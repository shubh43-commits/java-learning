package Challenges;

public class pyramind {
    // right half pyramid
    public static void main(String[] args) {
        System.out.println("Right half Pyramid");
        System.out.println();
        System.out.println("*");
        System.out.println("* *");
        System.out.println("* * *");
        System.out.println("* * * *");
        System.out.println("* * * * *");

        System.out.println();
        System.out.println("Reverse right half pyramid");
        System.out.println();
        System.out.println("* * * * *");
        System.out.println("* * * *");
        System.out.println("* * *");
        System.out.println("* *");
        System.out.println("*");

        System.out.println();
        System.out.println("left half pyramid");
        System.out.println();
        System.out.println("        *");
        System.out.println("      * *");
        System.out.println("    * * *");
        System.out.println("  * * * *");
        System.out.println("* * * * *");
    }
}
